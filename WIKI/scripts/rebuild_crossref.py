#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Rebuild crossref tag_index.md + tool_index.md from DB stats."""
import json
import os
from pathlib import Path
S = Path(__file__).resolve().parent          # WIKI/scripts
WIKI = Path(os.environ.get("BLENDER_WIKI_ROOT") or S.parent)   # WIKI
DB = WIKI/"db"/"wiki_database.json"
db = json.loads(DB.read_text(encoding="utf-8"))
stats = db.get("statistics", {})
top_tags = stats.get("top_tags", {})
top_tools = stats.get("top_tools", {})

tag_lines = ["# CROSS-REFERENCE: TAG INDEX", "", "_Autogenerated from DB stats. See `scripts/build_database.py`._", "",
 "## Top tags", "", "| Tag | Count |", "|---|---|"]
for tag, cnt in list(top_tags.items())[:30]:
    tag_lines.append(f"| `{tag}` | {cnt} |")
tag_lines += ["", "## By category", ""]
for cat, cnt in stats.get("by_category", {}).items():
    tag_lines.append(f"- **{cat}**: {cnt}")
tag_lines += ["", "## By language", ""]
for lang, cnt in stats.get("by_language", {}).items():
    tag_lines.append(f"- **{lang}**: {cnt}")
(WIKI/"crossref"/"tag_index.md").write_text("\n".join(tag_lines) + "\n", encoding="utf-8")

tool_lines = ["# CROSS-REFERENCE: TOOL INDEX", "", "_Autogenerated from DB stats._", "",
 "## MCP tools by usage", "", "| Tool | Count |", "|---|---|"]
for tool, cnt in list(top_tools.items())[:25]:
    tool_lines.append(f"| `{tool}` | {cnt} |")
tool_lines += ["", "## Notes", "- `execute_blender_code` is the universal fallback.",
 "- Prefer specific tools (`create_object`, `set_material`, Poly Haven) over raw code.",
 "- See `mcp/server-api.md` (v1 reference) + `setups/setup_06_custom_mcp_tools.md` for custom tools."]
(WIKI/"crossref"/"tool_index.md").write_text("\n".join(tool_lines) + "\n", encoding="utf-8")
print(f"OK crossref rebuilt: tags={len(top_tags)} tools={len(top_tools)}")
